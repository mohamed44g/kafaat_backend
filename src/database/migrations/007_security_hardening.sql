CREATE TABLE auth_sessions (
  id uuid PRIMARY KEY,
  token_hash char(64) NOT NULL UNIQUE,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  ip_hash char(64),
  user_agent_hash char(64),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (expires_at > created_at)
);

ALTER TABLE users
  ADD COLUMN mfa_secret_encrypted text,
  ADD COLUMN mfa_enabled boolean NOT NULL DEFAULT false;

CREATE TABLE auth_mfa_challenges (
  id uuid PRIMARY KEY,
  token_hash char(64) NOT NULL UNIQUE,
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  purpose varchar(16) NOT NULL CHECK (purpose IN ('setup', 'verify')),
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 5),
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_auth_mfa_challenges_expiry
  ON auth_mfa_challenges (expires_at);

CREATE INDEX idx_auth_sessions_user_active
  ON auth_sessions (user_id, expires_at DESC)
  WHERE revoked_at IS NULL;
CREATE INDEX idx_auth_sessions_expiry ON auth_sessions (expires_at);

CREATE TABLE login_attempts (
  identifier_hash char(64) PRIMARY KEY,
  attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  first_attempt_at timestamptz NOT NULL DEFAULT now(),
  locked_until timestamptz,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE security_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  action varchar(120) NOT NULL,
  resource_type varchar(80),
  resource_id varchar(180),
  outcome varchar(16) NOT NULL CHECK (outcome IN ('success', 'denied', 'failed')),
  request_id varchar(80),
  ip_hash char(64),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_security_audit_actor_time
  ON security_audit_log (actor_user_id, created_at DESC);
CREATE INDEX idx_security_audit_action_time
  ON security_audit_log (action, created_at DESC);

