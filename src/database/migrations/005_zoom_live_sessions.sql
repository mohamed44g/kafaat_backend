CREATE TABLE live_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(180) NOT NULL,
  description text,
  starts_at timestamptz NOT NULL,
  duration_minutes integer NOT NULL CHECK (duration_minutes BETWEEN 15 AND 1440),
  status varchar(24) NOT NULL DEFAULT 'scheduled'
    CHECK (status IN ('scheduled', 'live', 'ended', 'canceled', 'failed')),
  zoom_meeting_id varchar(32) NOT NULL UNIQUE,
  zoom_meeting_uuid varchar(160),
  zoom_join_url text NOT NULL,
  zoom_passcode varchar(32) NOT NULL,
  recording_enabled boolean NOT NULL DEFAULT false,
  created_by bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_live_sessions_schedule
  ON live_sessions (starts_at DESC, status);

