CREATE TYPE user_role_enum AS ENUM ('super_admin', 'admin', 'student');
CREATE TYPE subscription_status_enum AS ENUM ('active', 'expired', 'canceled');
CREATE TYPE subscription_provider_enum AS ENUM ('mada', 'apple_pay', 'stc_pay', 'card');

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(150) NOT NULL,
  email varchar(320) NOT NULL UNIQUE, phone varchar(24) NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL, role user_role_enum NOT NULL DEFAULT 'student',
  is_subscribed boolean NOT NULL DEFAULT false, subscription_ends_at timestamptz,
  avatar_url text, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_users_subscription ON users (is_subscribed, subscription_ends_at);
CREATE TABLE categories (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title varchar(120) NOT NULL UNIQUE, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE instructors (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(150) NOT NULL, bio text NOT NULL, avatar_url text, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE courses (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug varchar(180) NOT NULL UNIQUE, title varchar(180) NOT NULL, description text NOT NULL, thumbnail_url text,
  total_time bigint NOT NULL DEFAULT 0 CHECK (total_time >= 0), total_video integer NOT NULL DEFAULT 0 CHECK (total_video >= 0), is_published boolean NOT NULL DEFAULT false,
  instructor_id bigint NOT NULL REFERENCES instructors(id) ON DELETE RESTRICT, category_id bigint NOT NULL REFERENCES categories(id) ON DELETE RESTRICT, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_courses_category ON courses(category_id); CREATE INDEX idx_courses_instructor ON courses(instructor_id); CREATE INDEX idx_courses_published ON courses(is_published);
CREATE TABLE videos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title varchar(180) NOT NULL, description text, is_free boolean NOT NULL DEFAULT false, position integer NOT NULL,
  duration_seconds integer NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0), bunny_video_id varchar(120) UNIQUE, stream_status varchar(24) NOT NULL DEFAULT 'not_uploaded', thumbnail_url text,
  last_stream_event_at timestamptz, course_id bigint NOT NULL REFERENCES courses(id) ON DELETE CASCADE, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), UNIQUE(course_id, position)
);
CREATE INDEX idx_videos_course ON videos(course_id);
CREATE TABLE bunny_webhook_events (event_id uuid PRIMARY KEY, video_guid uuid NOT NULL, status integer NOT NULL, event_timestamp timestamptz NOT NULL, received_at timestamptz NOT NULL DEFAULT now());
CREATE INDEX idx_bunny_webhook_video_time ON bunny_webhook_events(video_guid,event_timestamp);
CREATE TABLE subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE, status subscription_status_enum NOT NULL,
  starts_at timestamptz NOT NULL, end_at timestamptz NOT NULL CHECK (end_at > starts_at), provider subscription_provider_enum NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_subscriptions_user_status_end ON subscriptions(user_id,status,end_at);
CREATE TABLE user_video_progress (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE, video_id bigint NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
  is_completed boolean NOT NULL DEFAULT false, watched_duration integer NOT NULL DEFAULT 0 CHECK (watched_duration >= 0), updated_at timestamptz NOT NULL DEFAULT now(), UNIQUE(user_id,video_id)
);
CREATE INDEX idx_progress_user ON user_video_progress(user_id); CREATE INDEX idx_progress_video ON user_video_progress(video_id);
